// Признаки финансовой пирамиды в одном сообщении. Каждый признак — объяснимое правило:
// что нашли, цитата, сила 0..1. Признаки не выносят вердикт, их взвешивает модель (model.ts).
// Шаблоны написаны по «каноническому» тексту (normalize.ts): казахские буквы сведены к русским,
// поэтому «қайтар» ищем как «кайтар», «күніне» — как «кунине».

import { normalize, type Normalized } from './normalize.ts';

export type SignalCategory = 'promise' | 'pressure' | 'referral' | 'payment' | 'proof' | 'complaint' | 'dampener';

export interface Signal {
  id: string;
  category: SignalCategory;
  title: string;
  detail: string;
  evidence: string[];
  strength: number;
}

export interface ReturnPromise {
  invest: number;
  receive: number;
  ratio: number;
  days: number | null;
  snippet: string;
}

export interface MessageSignals {
  norm: Normalized;
  signals: Signal[];
  returnPromise: ReturnPromise | null;
}

const L = '\\p{L}';
const B = `(?<!${L})`; // начало слова
const E = `(?!${L})`; // конец слова
const CUR = '(?:₸|тг|тенге)?';

function rx(source: string): RegExp {
  return new RegExp(source, 'gu');
}

function snippetsOf(canon: string, re: RegExp, limit = 3): string[] {
  const out: string[] = [];
  re.lastIndex = 0;
  for (const m of canon.matchAll(re)) {
    const start = Math.max(0, (m.index ?? 0) - 25);
    const end = Math.min(canon.length, (m.index ?? 0) + m[0].length + 25);
    out.push(canon.slice(start, end).trim());
    if (out.length >= limit) break;
  }
  return out;
}

