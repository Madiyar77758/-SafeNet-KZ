function signal(id: string, category: SignalCategory, title: string, detail: string, evidence: string[], strength: number): Signal {
  return { id, category, title, detail, evidence, strength: Math.max(0, Math.min(1, strength)) };
}

function formatAmount(value: number): string {
  return value.toLocaleString('ru-RU').replace(/ /g, ' ');
}

function formatPercent(value: number): string {
  return (value >= 10 ? Math.round(value).toString() : value.toFixed(1)).replace('.', ',');
}

// «Вложи 5к в наш проект» — вложение в «проект», а не в банк.
const INVEST_PROJECT = rx(`${B}(?:влож|инвест|вклад|закин|вкин|салым|акша сал)${L}* (?:${L}+ |\\d+ ){0,3}(?:в|на)? ?(?:наш|мой|этот|нашу|мою|эту|бизнес|онлайн|нов|государствен|инвестицион|международн|криптовалют|уникальн)${L}* (?:${L}+ )?(?:проект|клуб|фонд|платформ|пул|компани|систем|жоба|программ)${L}*`);
// Поддельные инвестплатформы «от имени государства»: «доходы от нефти для каждого гражданина».
const FAKE_PLATFORM = rx(
  [
    `(?:доход|дивиденд|прибыл)${L}* (?:от|с) (?:${L}+ ){0,2}(?:ресурс|нефт|газ|недр|природн)${L}*`,
    `гос\\.? ?программ${L}*|госпрограмм${L}*|одобрен${L}* правительств${L}*`,
    `(?:государствен|национальн|официальн)${L}* (?:инвестиц${L}* )?(?:платформ|программ|проект)${L}* (?:${L}+ |\\d+ ){0,6}(?:доход|дивиденд|получа|зарабат|инвест)${L}*`,
    `(?:казмунайгаз|казакгаз|кмг|самрук|нацбанк|национальн${L}* банк)${L}* (?:${L}+ |\\d+ ){0,6}(?:влож|инвест|дивиденд|получа|доход)${L}*`,
  ].join('|'),
);
const INVEST_RE = rx(INVEST);
const INVEST_OR_SEND_RE = rx(INVEST_OR_SEND);
const RECEIVE_RE = rx(RECEIVE);

function detect(text: string): MessageSignals {
  const norm = normalize(text);
  const c = norm.canon;
  const lower = text.toLowerCase();
  const signals: Signal[] = [];
  const has = (re: RegExp) => ((re.lastIndex = 0), re.test(c));
  // «х3 за 10 дней» — срок рядом с множителем тоже денежный контекст.
  const moneyContext = norm.requisites.length > 0 || /\d{3,}/.test(c) || has(INVEST_OR_SEND_RE) || has(RECEIVE_RE) || has(MONEY_WORDS) || has(DURATION) || has(IMPLICIT_DURATION);
  const promises = () => signals.some((s) => ['return', 'percent', 'multiplier', 'gift_circle'].includes(s.id));

  // Обещание дохода
  const ret = findReturn(c);
  if (ret && ret.ratio >= 1.2) {
    const perDay = ret.days ? (ret.ratio - 1) / ret.days : null;
    const strength = ret.ratio >= 1.5 || (perDay !== null && perDay >= 0.02) ? 1 : 0.6;
    const period = ret.days ? ` за ${ret.days < 1 ? `${Math.round(ret.days * 24)} ч` : `${Math.round(ret.days)} дн.`}` : '';
    signals.push(signal('return', 'promise', 'Нереалистичная доходность', `вложить ${formatAmount(ret.invest)} → получить ${formatAmount(ret.receive)}${period} (×${ret.ratio.toFixed(1).replace('.', ',')})`, [ret.snippet], strength));
  } else {
    const payback = paybackDays(c);
    if (payback !== null && payback <= 60) {
      signals.push(signal('return', 'promise', 'Нереалистичная доходность', `обещают окупить вложение за ${payback < 1 ? `${Math.round(payback * 24)} ч` : `${Math.round(payback)} дн.`}`, snippetsOf(c, PAYBACK), 0.8));
    }
  }

  // Проценты по займу — не доход; «3% в день на вклад» рядом со словом «кредит» — всё равно обещание.
  const loan = (has(LOAN) || has(MARKET)) && !has(INVEST_RE);
  let percentFound = loan;
  for (const m of loan ? [] : c.matchAll(PERCENT_PERIOD)) {
    const value = Number((m[1] ?? m[4]).replace(',', '.'));
    const unit = m[2] ?? m[3];
    const daily = dailyPercent(value, unit);
    if (daily >= 0.3) {
      signals.push(signal('percent', 'promise', 'Высокий процент за короткий срок', `${value}% (${unit}) ≈ ${formatPercent(daily)}% в день`, [m[0]], daily >= 1 ? 1 : 0.6));
      percentFound = true;
      break;
    }
  }
  if (!percentFound) {
    for (const m of c.matchAll(DEPOSIT_BONUS)) {
      if (Number(m[1] ?? m[2]) >= 10) {
        signals.push(signal('percent', 'promise', 'Высокий процент за короткий срок', `бонус ${m[1] ?? m[2]}% к вкладу`, [m[0]], 0.8));
        percentFound = true;
        break;
      }
    }
  }
  if (!percentFound) {
    for (const m of c.matchAll(PERCENT_OVER)) {
      const value = Number((m[1] ?? m[4]).replace(',', '.'));
      const days = m[2] ? durationDays(Number(m[2]), m[3]) : durationDays(1, m[5]);
      const daily = value / Math.max(days, 1);
      if (daily >= 0.3) {
        signals.push(signal('percent', 'promise', 'Высокий процент за короткий срок', `${value}% за ${Math.round(days)} дн. ≈ ${formatPercent(daily)}% в день`, [m[0]], daily >= 1 ? 1 : 0.6));
        percentFound = true;
        break;
      }
    }
  }
  if (!percentFound) {
    for (const m of c.matchAll(PERCENT_OVER_REV)) {
      const days = durationDays(Number(m[1] ?? 1) || 1, m[2]);
      const value = Number(m[3].replace(',', '.'));
      const daily = value / Math.max(days, 1);
      if (daily >= 0.3) {
        signals.push(signal('percent', 'promise', 'Высокий процент за короткий срок', `${value}% за ${Math.round(days)} дн. ≈ ${formatPercent(daily)}% в день`, [m[0]], daily >= 1 ? 1 : 0.6));
        percentFound = true;
        break;
      }
    }
  }
  if (!percentFound && has(TURNOVER)) {
    signals.push(signal('percent', 'promise', 'Высокий процент за короткий срок', 'процент «за оборот» — доход за круг без срока', snippetsOf(c, TURNOVER, 1), 0.8));
    percentFound = true;
  }
  const rate = percentFound ? null : rateFromStake(c);
  if (rate && rate.daily >= 0.3) {
    signals.push(signal('percent', 'promise', 'Высокий процент за короткий срок', `${formatAmount(rate.perPeriod)} ${rate.period} на вложение ${formatAmount(rate.stake)} ≈ ${formatPercent(rate.daily)}% в день`, [rate.snippet], rate.daily >= 1 ? 1 : 0.6));
  }

  // «бонусы х2 на технику», «кешбэк х3» — множитель бонусов магазина, а не денег участника.
  const multRaw = [MULTIPLIER_RAW.exec(lower), MULTIPLIER_POST.exec(lower)].find((m) => m && !/(?:бонус|балл|кешб|кэшб|скидк|акци)\p{L}*\s*$/u.test(lower.slice(0, m.index))) ?? null;
  const multValue = multRaw ? Number(multRaw[1].replace(',', '.')) : 0;
  if (moneyContext && ((multValue >= 1.5 && multValue <= 100) || has(MULTIPLIER_WORDS))) {
    const fromRaw = multValue >= 1.5 && multValue <= 100 && multRaw;
    signals.push(signal('multiplier', 'promise', 'Обещание умножить деньги', fromRaw ? `«${multRaw[0].trim()}»` : 'умножение вложений', fromRaw ? [multRaw[0]] : snippetsOf(c, MULTIPLIER_WORDS), 1));
  }
  const rateClaim = !rate && (has(RATE_A) || has(RATE_B)) && !has(JOBISH);
  const recruit = has(RECRUIT) && /\d{3,}/.test(c) && (has(INVEST_RE) || has(RECEIVE_RE));
  if (has(INCOME_CLAIM) || rateClaim || recruit) {
    const evidence = has(INCOME_CLAIM) ? snippetsOf(c, INCOME_CLAIM) : rateClaim ? [...snippetsOf(c, RATE_A), ...snippetsOf(c, RATE_B)].slice(0, 2) : snippetsOf(c, RECRUIT, 1);
    signals.push(signal('income_claim', 'promise', 'Заявления о доходе в день', recruit && !rateClaim ? 'хвастаются доходом и зовут присоединиться' : 'хвастаются регулярным доходом', evidence, 0.7));
  }
  if (has(GUARANTEE)) signals.push(signal('guarantee', 'promise', 'Гарантия дохода без риска', 'обещание гарантированной прибыли', snippetsOf(c, GUARANTEE), 0.8));
  if (has(EASY)) signals.push(signal('easy', 'promise', 'Лёгкий пассивный доход', 'доход без усилий', snippetsOf(c, EASY), 0.7));
  if (has(DENIAL)) signals.push(signal('denial', 'promise', 'Уверения «это не пирамида»', 'заранее отрицают обман', snippetsOf(c, DENIAL), 0.8));
  if (has(TASK) && has(ENTRY_FEE) && /\d{3,}/.test(c)) {
    signals.push(signal('invest_call', 'promise', 'Призыв вложить деньги', 'платный вход за право выполнять «задания»', [...snippetsOf(c, TASK, 1), ...snippetsOf(c, ENTRY_FEE, 1)], 1));
  } else if (has(FAKE_PLATFORM)) {
    signals.push(signal('invest_call', 'promise', 'Призыв вложить деньги', 'инвестиции «от имени государства» или нацкомпании', snippetsOf(c, FAKE_PLATFORM, 1), 1));
  } else if (has(INVEST_PROJECT)) {
    signals.push(signal('invest_call', 'promise', 'Призыв вложить деньги', 'зовут вложить деньги в «проект» или «клуб»', snippetsOf(c, INVEST_PROJECT, 1), 1));
  } else if (has(INVEST_RE) && /\d{3,}/.test(c)) {
    signals.push(signal('invest_call', 'promise', 'Призыв вложить деньги', 'вложение с суммой', snippetsOf(c, INVEST_RE, 1), 0.5));
  }

  // Давление
  if (has(SCARCITY)) signals.push(signal('scarcity', 'pressure', 'Искусственный дефицит', 'мало мест / последний набор', snippetsOf(c, SCARCITY), 0.9));
  if (has(URGENCY)) signals.push(signal('urgency', 'pressure', 'Давление срочностью', 'торопят с решением', snippetsOf(c, URGENCY), 0.7));

  // Вербовка
  const refMoney = has(REF_PERCENT);
  if (has(REFERRAL)) signals.push(signal('referral', 'referral', 'Доход за приглашённых', refMoney ? 'процент с вложений приглашённых' : 'реферальная модель', snippetsOf(c, REFERRAL), refMoney ? 1 : 0.9));
  if (has(LEVELS)) signals.push(signal('levels', 'referral', 'Многоуровневая структура', 'линии / уровни участников', snippetsOf(c, LEVELS), 0.8));
  if (has(GIFT_CIRCLE)) signals.push(signal('gift_circle', 'referral', 'Схема «круг / ячейка» с дарением', 'деньги новых участников идут старым', snippetsOf(c, GIFT_CIRCLE), 1));

  // Оплата
  const requisites = norm.requisites;
  if (requisites.length > 0 || has(PERSONAL_TRANSFER)) {
    const shown = requisites.map((r) => maskRequisite(r.value, r.type)).join(', ');
    signals.push(
      signal('personal_transfer', 'payment', 'Перевод на личную карту / номер', shown ? `реквизиты: ${shown}` : 'просят перевести на карту или по номеру', [...requisites.map((r) => r.raw), ...snippetsOf(c, PERSONAL_TRANSFER, 2)], requisites.length > 0 ? 1 : 0.7),
    );
  }
  if (has(KASPI)) signals.push(signal('kaspi', 'payment', 'Упоминание Kaspi', 'Kaspi как способ оплаты', snippetsOf(c, KASPI, 1), 0.5));

  // Подтверждения, жалобы
  const thanks = has(THANKS) && has(PAYOUT_CONTEXT);
  if (has(TESTIMONIAL) || thanks) signals.push(signal('testimonial', 'proof', 'Отзыв о выплате («прогрев»)', 'хвалят выплаты', [...snippetsOf(c, TESTIMONIAL), ...(thanks ? snippetsOf(c, THANKS, 1) : [])], 0.8));
  if (has(COMPLAINT)) signals.push(signal('complaint', 'complaint', 'Жалоба на невыплату', 'участник не может вернуть деньги', snippetsOf(c, COMPLAINT), 0.9));
  if (norm.moneyEmoji >= 2 || norm.hypeEmoji >= 3) signals.push(signal('emoji', 'pressure', 'Эмодзи денег и ажиотажа', `деньги ×${norm.moneyEmoji}, ажиотаж ×${norm.hypeEmoji}`, [], 0.5));

  // Снижающие
  if (has(WARNING) && !has(DENIAL)) signals.push(signal('warning', 'dampener', 'Предупреждение о мошенничестве', 'текст предостерегает, а не зазывает', snippetsOf(c, WARNING), 1));
  if (has(DOUBT)) signals.push(signal('doubt', 'dampener', 'Пересказ или сомнение', 'человек спрашивает, не обман ли это', snippetsOf(c, DOUBT), 1));
  const annual = [...c.matchAll(ANNUAL)].map((m) => Number((m[1] ?? m[2]).replace(',', '.')));
  // «Лицензия есть, 2% в день» — легальный продукт таких процентов не обещает, признак не снижает риск.
  const unrealistic = signals.some((s) => s.id === 'return' || s.id === 'multiplier' || (s.id === 'percent' && s.strength >= 0.6));
  if ((has(LICENSED) || annual.length > 0) && !unrealistic) {
    const realistic = annual.length > 0 && annual.every((v) => v <= 30);
    signals.push(signal('licensed', 'dampener', 'Признаки легального финансового продукта', realistic ? `реалистичная ставка ${annual.join(', ')}% годовых` : 'депозит, лицензия, рассрочка', snippetsOf(c, LICENSED), realistic ? 1 : 0.6));
  }
  if (has(FREE_REWARD) && !promises() && !refMoney && !has(DENIAL)) signals.push(signal('free_reward', 'dampener', 'Награда не деньгами', 'скидка, бесплатное занятие, подарок', snippetsOf(c, FREE_REWARD), 1));
  if (has(LEGIT_PAYOUT) || has(JOBISH)) signals.push(signal('legit_payout', 'dampener', 'Законные выплаты', 'зарплата, пособие, работа по найму', [...snippetsOf(c, LEGIT_PAYOUT), ...snippetsOf(c, JOBISH)].slice(0, 3), 1));
  if (/\?\s*$/.test(text.trim()) && !promises() && !has(RECRUIT_QUESTION)) signals.push(signal('question', 'dampener', 'Сообщение — вопрос', 'спрашивают, а не предлагают', [], 0.6));

  return { norm, signals, returnPromise: ret };
}

