// Вложение. «Скинь/переведи/подари» сами по себе — обычный перевод (сбор на подарок учителю),
// поэтому для признака «призыв вложить» берём только INVEST, а для пары «вложи → получи» — и переводы тоже.
const INVEST = `${B}(?<!без )(?:влож|вклад|инвест|салым|салсан|салып|салыныз|салады|салу${E}|сал${E}|салд|салган|салгам|закин|закид|вкид|вкин|вход${E}|входа${E}|куп${L}* (?:место|мест|пакет|тариф|вип|дол[юи])|оплат${L}* (?:вип|пакет|тариф|участи|вход|регистрац)|стартов${L}* (?:капитал|взнос|сумм)|(?:зайти|заходи${L}*|заход${L}*|зашел|зашла|входишь|начни|начать|стартуй|старт) (?:с|за)(?= \\d)|салас)`;
// «Взнос», «внеси» — обычное слово сборов («взнос на ремонт подъезда»), поэтому только в паре «внеси → забери».
const INVEST_OR_SEND = `${INVEST}|${B}(?:внес|внос|взнос|кин[ьу]|кида|скин|скида|отправ|переве|перевод|пополн|дари|отда|всего${E}|жибер|аудар(?!ма)|сыйла|жарна|полож|оплачива|ставк|из(?= \\d))`;
const RECEIVE = `${B}(?:получ|забер|забира|вывед|вывод|вывож|выплат|верн|возвра|сним|снял|аласын|аласыз|алыныз|алады|алдым|ал${E}|табыс|табы(?:ныз|сыз|сын|амыз|амын|асыз|асын|ады)|тап(?:тым|тык|ты|асын|асыз|амын|амыз)${E}|кайтар|каитар|кайтты|прибыл|заработ|доход|кирис|пайда|профит|выход${E}|выходишь|выход${L}* с(?= \\d)|на выходе|делаем|сделаем|сделай|превраща|станет|будет у тебя|у тебя|на (?:твоей|вашей|твою|вашу) карт|на счет|прилет|придет|приход|капа|капн|начисл|поступ|выигр|выйгр|осед|осип|на руки|подня|поднима|тус(?:ип|еди|ети|ед)|шыгар)`;
const DURATION = /(\d+)\s*(час|сагат|ден|дня|дней|сут|таулик|кун|недел|апта|мес|ай(?!\p{L})|айда)/gu;
// «за неделю», «через сутки», «бир аптада», «уже в пятницу», «ертен» — срок без числа.
const IMPLICIT_DURATION = /(?:за|через|бир|в течение|в течении)\s+(час|сутки|суток|день|неделю|недели|месяц|кун|апта|ай|круг|таулик)|(?<!\p{L})(завтра|послезавтра|ертен|бугин|вечером|к вечеру|к пятнице|к выходным|в пятницу|в субботу|в воскресенье|в понедельник)(?!\p{L})/gu;
const MONEY_WORDS = rx(`${B}(?:деньг|денег|акша|салым|вклад|влож|тенге|тг${E}|каспи|выплат|прибыл|доход|табыс|пайда|реквизит)`);

function durationDays(num: number, unit: string): number {
  if (unit.startsWith('час') || unit.startsWith('сагат')) return num / 24;
  if (unit.startsWith('недел') || unit.startsWith('апта')) return num * 7;
  if (unit.startsWith('мес') || unit.startsWith('ай') || unit.startsWith('круг')) return num * 30;
  return num;
}

function implicitDays(word: string): number {
  if (/пятниц|суббот|воскресен|понедельник|выходн/.test(word)) return 5;
  if (word === 'послезавтра') return 2;
  if (/завтра|ертен|бугин|вечер/.test(word)) return 1;
  return durationDays(1, word);
}

/** «вложи 5000 получи 10000 за 3 дня», «5000 салсан 3 кунде 10000 аласын», «5000 → 15000», «из 20к — 100к». */
export function findReturn(canon: string): ReturnPromise | null {
  let best: ReturnPromise | null = null;
  const parts = canon.split(/[.!?\n;]+/).map((s) => s.trim()).filter(Boolean);
  // Обещание бывает разбито на два предложения: «Заходишь за 30 000. Когда заполнятся ячейки — приходит 120 000».
  // Для пары соседних предложений нужны оба глагола: «вложить» и «получить».
  const windows = [...parts.map((text) => ({ text, joined: false })), ...parts.slice(1).map((text, i) => ({ text: `${parts[i]}, ${text}`, joined: true }))];
  for (const { text: raw, joined } of windows) {
    // «от 200000 до 400000», «5000-10000» — диапазон зарплаты или цены, а не «вложил → получил».
    const sentence = raw.replace(/от\s+\d+\s*(?:₸|тг|тенге)?\s*до\s+\d+|\d+-\d+/g, (m) => ' '.repeat(m.length));
    const durations: { start: number; end: number; days: number }[] = [];
    for (const m of sentence.matchAll(DURATION)) {
      durations.push({ start: m.index ?? 0, end: (m.index ?? 0) + m[0].length, days: durationDays(Number(m[1]), m[2]) });
    }
    for (const m of sentence.matchAll(IMPLICIT_DURATION)) {
      durations.push({ start: m.index ?? 0, end: (m.index ?? 0) + m[0].length, days: m[1] ? durationDays(1, m[1]) : implicitDays(m[2]) });
    }
    const amounts: { pos: number; value: number }[] = [];
    for (const m of sentence.matchAll(/\d+/g)) {
      const pos = m.index ?? 0;
      const value = Number(m[0]);
      if (value < 100 || durations.some((d) => pos >= d.start && pos < d.end)) continue;
      if (/^\s*%/.test(sentence.slice(pos + m[0].length))) continue;
      amounts.push({ pos, value });
    }
    // «положила 100 тысяч, через месяц сняла 130» — вторая сумма в тех же тысячах.
    if (amounts.some((a) => a.value >= 10000)) {
      for (const a of amounts) if (a.value < 1000 && /(?:сня|получ|вывел|забрал|полож|влож|салд|алд)\p{L}*\s*$/u.test(sentence.slice(Math.max(0, a.pos - 20), a.pos))) a.value *= 1000;
    }
    if (amounts.length < 2) continue;
    const investPos = [...sentence.matchAll(rx(INVEST_OR_SEND))].map((m) => m.index ?? 0);
    const receivePos = [...sentence.matchAll(rx(RECEIVE))].map((m) => m.index ?? 0);
    const arrow = /\d+\s*(?:→|->|=>|=|—>|до|в|-га|ка|ке|га)\s*\d+/u.test(sentence);
    const hasVerb = investPos.length > 0 || receivePos.length > 0;
    const paired = investPos.length > 0 && receivePos.length > 0;
    // «10к → 25к за неделю» — стрелка между суммами со сроком или «в месяц» говорит сама за себя.
    const direct = /(\d{3,})\s*(?:→|->|=>|—>)\s*(\d{3,})/u.exec(sentence);
    if (!hasVerb && direct && !joined && Number(direct[2]) > Number(direct[1]) && (durations.length > 0 || /в (?:день|неделю|месяц)|ежедневно|ежемесячно|кунине|айына/u.test(sentence))) {
      const ratio = Number(direct[2]) / Number(direct[1]);
      const days = durations.length ? Math.max(...durations.map((d) => d.days)) : null;
      if (ratio <= 1000 && (!best || ratio > best.ratio)) best = { invest: Number(direct[1]), receive: Number(direct[2]), ratio, days, snippet: raw.trim() };
      continue;
    }
    if (!hasVerb || !(paired || arrow || durations.length > 0) || (joined && !paired)) continue;

    const nearest = (positions: number[], exclude?: number) =>
      amounts
        .filter((a) => a.pos !== exclude)
        .map((a) => ({ a, d: positions.length ? Math.min(...positions.map((p) => Math.abs(p - a.pos))) : 0 }))
        .sort((x, y) => x.d - y.d)[0]?.a;
    let invest = investPos.length ? nearest(investPos) : amounts[0];
    let receive = receivePos.length ? nearest(receivePos, invest?.pos) : amounts.find((a) => a.pos > (invest?.pos ?? -1) && a.pos !== invest?.pos);
    if (!invest || !receive) continue;
    if (receive.value < invest.value) [invest, receive] = [receive, invest];
    if (receive.value <= invest.value) continue;
    const ratio = receive.value / invest.value;
    if (ratio > 1000) continue; // «5000 и 7 000 000» — скорее разные числа, чем доходность
    const days = durations.length ? Math.max(...durations.map((d) => d.days)) : null;
    const candidate = { invest: invest.value, receive: receive.value, ratio, days, snippet: raw.trim() };
    if (!best || candidate.ratio > best.ratio) best = candidate;
  }
  return best;
}

// «вклад окупится за 3 дня», «за 3 дня окупается», «отбивается за день», «3 кунде озин-ози актайды»
const PAYBACK_VERB = `(?:окуп|отбива|отбил|актай|актал)${L}*`;
const PAYBACK_UNIT = `(час|сутки|суток|день|дня|дней|ден${E}|недел${L}*|мес${L}*|кун${L}*|апта${L}*)`;
const PAYBACK = rx(
  `${PAYBACK_VERB} (?:${L}+ ){0,2}(?:за|через) (\\d+ |пару )?${PAYBACK_UNIT}|(?:за|через) (\\d+ |пару )?${PAYBACK_UNIT} (?:${L}+ ){0,1}${PAYBACK_VERB}|(\\d+) (кунде|аптада|айда) (?:${L}+ ){0,2}${PAYBACK_VERB}`,
);

function paybackDays(canon: string): number | null {
  PAYBACK.lastIndex = 0;
  const m = PAYBACK.exec(canon);
  if (!m) return null;
  const count = (n: string | undefined) => (n === 'пару ' ? 2 : Number(n ?? 1) || 1);
  if (m[2]) return durationDays(count(m[1]), m[2]);
  if (m[4]) return durationDays(count(m[3]), m[4]);
  return durationDays(Number(m[5]), m[6]);
}

// Доход за период на сумму вложения: «купи место за 20 000, получай 2 000 ежедневно», «VIP за 10 000 — 3 000 в день».
const RATE_PERIOD = '(ежедневно|в день|каждый день|в сутки|кунине|кун сайын|в неделю|каждую неделю|аптасына|апта сайын|в месяц|айына|ай сайын|каждый месяц)';
const RATE_VERB = `(?:получа|получи|зарабатыва|доход|прибыл|начисл|выплат|табыс|табы|капа|приход|принос|профит|пассив|кирис|пайда|аласы|алас|шыгар|тус)${L}*`;
// Сумма может быть диапазоном: «600000-700000».
const RATE_A = rx(`${RATE_VERB} (?:от |по |до )?(\\d{3,})(?:-\\d+)? ?${CUR} ?${RATE_PERIOD}`);
const RATE_B = rx(`${RATE_PERIOD} (?:по )?(\\d{3,})(?:-\\d+)? ?${CUR}${L}* ?${RATE_VERB}`);
const STAKE = rx(`(?:влож|вклад|инвест|салым|взнос|вход|тиркелу|регистрац|вип|пакет|тариф|место|депозит|пополн|оплачива|оплати|активац|сал|салып|толтыр)${L}* (?:от |за |в |на |всего |доступа за )?(\\d{3,})|(\\d{3,}) ?${CUR}${L}* ?(?:салып|салсан|салсаныз|салдым|салганмын|влож${L}*|вклад${L}*|инвест${L}*|толтыр${L}*)`);
// «1000 ₸ прибыли за каждые вложенные 1000 ₸ в неделю»
const PER_UNIT = rx(`(\\d{3,}) ?${CUR} (?:прибыли |дохода )?(?:за|с) кажд${L}* (?:вложенн${L}* )?(\\d{3,}) ?${CUR} ?${RATE_PERIOD}?`);

function periodDays(period: string | undefined): number {
  if (!period) return 7;
  if (/недел|апта/.test(period)) return 7;
  if (/мес|ай/.test(period)) return 30;
  return 1;
}

/** Процент в день из «доход N за период» и суммы вложения. */
function rateFromStake(canon: string): { daily: number; snippet: string; perPeriod: number; stake: number; period: string } | null {
  PER_UNIT.lastIndex = 0;
  const unit = PER_UNIT.exec(canon);
  if (unit) {
    const days = periodDays(unit[3]);
    return { daily: (Number(unit[1]) / Number(unit[2]) / days) * 100, snippet: unit[0], perPeriod: Number(unit[1]), stake: Number(unit[2]), period: unit[3] ?? 'неделю' };
  }
  for (const re of [RATE_A, RATE_B]) {
    re.lastIndex = 0;
    const m = re.exec(canon);
    if (!m) continue;
    const perPeriod = Number(re === RATE_A ? m[1] : m[2]);
    const period = re === RATE_A ? m[2] : m[1];
    STAKE.lastIndex = 0;
    for (const s of canon.matchAll(STAKE)) {
      const stake = Number(s[1] ?? s[2]);
      if (stake && stake !== perPeriod) return { daily: (perPeriod / periodDays(period) / stake) * 100, snippet: `${s[0]} … ${m[0]}`, perPeriod, stake, period };
    }
  }
  return null;
}

