// Повествование о чужой схеме в прошедшем времени (новости): «люди надеялись получить 100%», «вкладчикам обещали».
const NARRATIVE = rx(
  `люди надеял${L}*|надеялись${E}|(?:им|людям|вкладчикам|участникам|салымшыларга) (?:${L}+ ){0,2}(?:обещал|уаде)${L}*|(?:они|олар|организатор${L}*|подозреваем${L}*|фигурант${L}*|уйымдастырушы${L}*|котор${L}*) (?:${L}+ |\\d+ ){0,4}(?:вовлек|привлек|собрал|похитил|обещал|принимал|обманул|жинаган|тартты|шакырган|уаде еткен)${L}*|вовлекли|тартылган|уаде етип|обещавш${L}* (?:вкладчик|участник|людям)${L}*|уйымдастырган|под названием`,
);
// Явное предупреждение о том, что описанное — схема: «там схема», «не ведитесь», «бұл алаяқтық».
const STRONG_WARNING = rx(
  `(?:это|ето|там|тут) (?:схема|пирамида|лохотрон|развод|мошенничество)${E}|бул (?:пирамида|алаяктык|алдау|развод)${E}|(?:—|-|является) (?:это )?(?:мошенничеств|пирамид|развод|лохотрон|алаяктык)${L}*|не ведит${L}*|выходите из${L}*|не вступайте|не переводите|сенбени${L}*|аударманы${L}*|абай болыныздар|абайла${L}*`,
);
const PROMISE_IDS = ['return', 'percent', 'multiplier', 'income_claim', 'gift_circle', 'referral', 'invest_call', 'guarantee'];

export function analyzeMessage(text: string): MessageSignals {
  const result = detect(text);
  const ids = new Set(result.signals.map((s) => s.id));
  const cautious = ids.has('warning') || ids.has('doubt') || ids.has('question') || ids.has('complaint') || text.includes('?');
  const promised = result.signals.filter((s) => PROMISE_IDS.includes(s.id));
  const c = result.norm.canon;
  if (promised.length === 0 || ids.has('denial')) return result;
  let evidence = snippetsOf(c, NARRATIVE, 1);
  if (evidence.length === 0 && ids.has('warning')) evidence = snippetsOf(c, STRONG_WARNING, 1);
  if (evidence.length === 0 && !cautious) return result;
  if (evidence.length === 0) evidence = snippetsOf(c, REPORTED, 1);
  if (evidence.length === 0 && /[«"“„']/.test(text)) {
    const outside = new Set(detect(text.replace(QUOTED, ' ')).signals.map((s) => s.id));
    const quoted = promised.filter((s) => !outside.has(s.id));
    evidence = quoted.length ? (text.match(QUOTED) ?? []).slice(0, 2) : [];
  }
  if (evidence.length) {
    // Чужие слова весят меньше: признаки схемы остаются видны аналитику, но с пометкой «в цитате».
    for (const s of result.signals) {
      if (s.category === 'dampener' || s.category === 'complaint') continue;
      s.strength = Math.round(s.strength * 0.35 * 100) / 100;
      s.detail = `${s.detail} — в цитате`;
    }
    result.signals.push(signal('reported', 'dampener', 'Обещание в цитате или пересказе', 'человек пересказывает чужое предложение, а не делает его', evidence, 1));
  }
  return result;
}

export function maskRequisite(value: string, type: 'phone' | 'card' | 'iban'): string {
  if (type === 'phone') return `+${value.slice(0, 1)} ${value.slice(1, 4)} *** ** ${value.slice(-2)}`;
  if (type === 'card') return `${value.slice(0, 4)} **** **** ${value.slice(-4)}`;
  return `${value.slice(0, 4)}…${value.slice(-4)}`;
}
